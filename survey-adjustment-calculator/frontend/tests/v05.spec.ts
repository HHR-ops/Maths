import { test, expect } from '@playwright/test'
import path from 'node:path'

test('xlsx template imports atomically and exposes equation steps, matrix links, and four-method comparison', async ({ page }) => {
  await page.goto('/'); await expect(page.getByTestId('stat-n')).toHaveText('5')
  await page.getByRole('button', { name: '批量导入', exact: true }).click()
  const downloading = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Excel 模板', exact: true }).click()
  const file = path.resolve('../qa/v05-water-template.xlsx')
  await (await downloading).saveAs(file)
  await page.getByLabel('批量导入方式', { exact: true }).selectOption('replace')
  await page.getByLabel('批量数据文件', { exact: true }).setInputFiles(file)
  await expect(page.locator('.import-table-tabs')).toContainText('控制点')
  await page.getByRole('button', { name: '检查并预览', exact: true }).click()
  await expect(page.getByTestId('import-validation')).toContainText('数据校验通过')
  await expect(page.getByTestId('import-validation')).toContainText('n=5，t=3，r=2')
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: '../qa/v05-import.png', fullPage: true })
  await page.getByRole('button', { name: '替换并导入', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('button', { name: '计算平差', exact: true }).click()
  await expect(page.locator('.solution-summary')).toContainText('平差已完成')
  await page.getByRole('tab', { name: '计算步骤', exact: true }).click()
  await expect(page.locator('.steps-navigation button')).toHaveCount(7)
  await page.locator('.steps-navigation button').nth(1).click()
  await page.getByRole('button', { name: '定位 O1:ΔH', exact: true }).click()
  await expect(page.locator('.inspector .property-title')).toContainText('O1')
  await page.getByRole('button', { name: '四法对照', exact: true }).click()
  await expect(page.getByTestId('method-comparison').locator('tbody tr')).toHaveCount(4)
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: '../qa/v05-steps.png', fullPage: true })
})

test('column mapping can correct a failed preview while the current project remains untouched', async ({ page }) => {
  await page.goto('/'); await expect(page.getByTestId('stat-n')).toHaveText('5')
  await page.getByRole('button', { name: '批量导入', exact: true }).click()
  await page.getByLabel('批量数据文件', { exact: true }).setInputFiles({ name: 'points.csv', mimeType: 'text/csv', buffer: Buffer.from('标识,高(mm),错误列,已知\nN1,100000,abc,是\nN2,101200,def,否\n') })
  await page.getByLabel('导入表格用途', { exact: true }).selectOption('points')
  await page.getByLabel('批量导入方式', { exact: true }).selectOption('replace')
  await page.getByLabel('映射 name', { exact: true }).selectOption('0')
  await page.getByLabel('映射 H', { exact: true }).selectOption('2')
  await page.getByLabel('映射 fixed', { exact: true }).selectOption('3')
  await page.getByRole('button', { name: '检查并预览', exact: true }).click()
  await expect(page.getByTestId('import-validation')).toContainText('尚未写入项目')
  await expect(page.getByTestId('stat-n')).toHaveText('5')
  await expect(page.getByRole('button', { name: '替换并导入', exact: true })).toBeDisabled()
  await page.getByLabel('映射 H', { exact: true }).selectOption('1')
  await expect(page.getByTestId('import-validation')).toHaveCount(0)
  await page.getByRole('button', { name: '检查并预览', exact: true }).click()
  await expect(page.getByTestId('import-validation')).toContainText('数据校验通过')
  await page.getByRole('button', { name: '替换并导入', exact: true }).click()
  await expect(page.getByTestId('stat-n')).toHaveText('0')
  await page.getByRole('tab', { name: '控制点', exact: true }).click()
  await expect(page.locator('.data-panel tbody')).toContainText('101.2')
  await page.getByRole('button', { name: '撤销', exact: true }).click()
  await expect(page.getByTestId('stat-n')).toHaveText('5')
})

test('gross-error diagnostics highlight the observation, disable the whole observation, and compare recalculation', async ({ page }) => {
  await page.goto('/'); await expect(page.getByTestId('stat-n')).toHaveText('5')
  const project = { format: 'survey-network-project', version: 1, name: '粗差检验例', family: '水准网', method: 'indirect', constraints: [],
    points: { A: { X: 0, Y: 0, H: 100, Z: 0, fixed: ['H'] }, B: { X: 80, Y: 120, H: 100, Z: 0, fixed: [] } },
    observations: Array.from({ length: 10 }, (_, i) => ({ id: 'O'+(i+1), kind: 'height', points: ['A', 'B'], value: i === 9 ? 1.01 : 1, sigma: .001, covariance: null, components: ['H'], enabled: true })) }
  await page.getByLabel('导入项目文件', { exact: true }).setInputFiles({ name: 'blunder.net.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(project)) })
  await expect(page.getByTestId('stat-n')).toHaveText('10')
  await page.getByRole('button', { name: '实测平差', exact: true }).click()
  await page.getByRole('button', { name: '计算平差', exact: true }).click()
  await expect(page.locator('.solution-summary')).toContainText('平差已完成')
  await page.getByRole('tab', { name: '粗差诊断', exact: true }).click()
  await expect(page.locator('.diagnostics-panel')).toContainText('1 条观测被标记')
  await page.getByLabel('仅看疑似异常', { exact: true }).check()
  await expect(page.locator('.diagnostic-scroll tbody tr')).toHaveCount(1)
  await expect(page.locator('.diagnostic-scroll tbody')).toContainText('O10')
  await expect(page.locator('.flagged-edge')).toHaveCount(1)
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: '../qa/v05-diagnostics.png', fullPage: true })
  await page.getByRole('button', { name: '停用并复算', exact: true }).click()
  await expect(page.getByTestId('stat-n')).toHaveText('9')
  await expect(page.locator('.recalculation-comparison tbody tr')).toHaveCount(5)
  await expect(page.locator('.diagnostics-panel')).toContainText('0 条观测被标记')
  await page.getByRole('button', { name: '撤销', exact: true }).click()
  await expect(page.getByTestId('stat-n')).toHaveText('10')
  await expect(page.locator('.flagged-edge')).toHaveCount(0)
})

