import { test, expect, type Page } from '@playwright/test'
import knowledge from '../src/knowledge.json' with { type: 'json' }

async function ready(page: Page) {
  await page.goto('/')
  await expect(page.getByTestId('stat-n')).toHaveText('5')
  await page.getByRole('button', { name: '理论与知识', exact: true }).click()
  await expect(page.locator('.theory-article h2')).toHaveText(knowledge.articles[0].title)
}
async function topic(page: Page, id: string) {
  const a = knowledge.articles.find(a => a.id === id)!
  await page.locator('.theory-chapter').getByRole('button', { name: a.title, exact: false }).click()
  await expect(page.locator('.theory-article h2')).toHaveText(a.title)
}
const metric = (page: Page, label: string) => page.locator('[data-metric="'+label+'"]')

test('all theory chapters, formulas, references, glossary and self checks work offline', async ({ page }) => {
  const errors: string[] = [], external: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  page.on('request', r => { if (!r.url().startsWith('http://127.0.0.1:8877')) external.push(r.url()) })
  await ready(page)
  await expect(page.locator('.theory-chapter')).toHaveCount(6)
  await expect(page.locator('.theory-chapter>button')).toHaveCount(13)
  for (const a of knowledge.articles) {
    await topic(page, a.id)
    await expect(page.locator('.theory-section')).toHaveCount(a.sections.length)
    await expect(page.locator('.katex-error')).toHaveCount(0)
    await expect(page.locator('.theory-sources a')).toHaveCount(a.sources.length)
    await page.locator('.theory-quiz button').nth(a.quiz.answer).click()
    await expect(page.locator('.theory-quiz [role=status]')).toContainText('回答正确')
  }
  await page.getByLabel('搜索理论知识').fill('Holm')
  await expect(page.locator('.search-count')).toContainText('找到')
  await expect(page.locator('.theory-chapter>button')).not.toHaveCount(13)
  await page.getByLabel('搜索理论知识').fill('不存在的检索词')
  await expect(page.locator('.theory-search-empty')).toBeVisible()
  await page.getByRole('button', { name: '清除理论搜索' }).click()
  await page.getByRole('button', { name: '符号速查', exact: true }).click()
  await expect(page.locator('.theory-glossary')).toContainText('v = L̂ − L')
  await topic(page, 'models')
  for (const width of [1440,1280,1060]) {
    await page.setViewportSize({ width, height: 960 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    expect(await page.locator('.theory-article').evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
  }
  await page.setViewportSize({ width: 1440, height: 1050 })
  await page.getByRole('button', { name: '符号速查', exact: true }).click()
  await page.evaluate(() => { window.scrollTo(0,0); document.querySelector('.theory-toc')!.scrollTop=0 })
  await page.screenshot({ path: '../qa/v06-theory-models.png', fullPage: true })
  expect(errors).toEqual([]); expect(external).toEqual([])
})

test('normal, propagation and weighted mean experiments update and reject invalid input', async ({ page }) => {
  await ready(page)
  await topic(page, 'random')
  await expect(metric(page, '区间内概率')).toContainText('68.268949')
  await page.getByLabel('区间半宽 k（σ 的倍数）').fill('3')
  await expect(metric(page, '区间内概率')).toContainText('99.73002')
  await topic(page, 'propagation')
  await expect(metric(page, '输出标准差')).toContainText('5')
  await page.getByLabel('相关系数 ρ', { exact: true }).fill('.5')
  await expect(metric(page, '输出标准差')).toContainText('6.082763')
  await page.getByLabel('计算关系').selectOption('-1')
  await expect(metric(page, '输出标准差')).toContainText('3.605551')
  await page.getByLabel('输入 1 标准差（mm）').fill('')
  await expect(page.locator('.lab-error')).toBeVisible()
  await expect(metric(page, '输出标准差')).toHaveCount(0)
  await page.getByRole('button', { name: '恢复例题', exact: true }).click()
  await expect(metric(page, '输出标准差')).toContainText('5')
  await topic(page, 'applications')
  await expect(metric(page, '加权平均值')).toContainText('9.777778')
  await expect(metric(page, 'vᵀPv')).toContainText('1.888889')
  await expect(page.locator('.theory-experiment tbody tr')).toHaveCount(3)
})

