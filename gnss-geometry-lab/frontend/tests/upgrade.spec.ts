import {test,expect} from '@playwright/test'
const ready=async(page:import('@playwright/test').Page)=>{await page.goto('/');await expect(page.getByTestId('metric-PDOP')).toHaveText('1.82')}
test('a whole satellite drag is one undo step; redo restores the final geometry',async({page})=>{
  await ready(page)
  const original=await page.evaluate(()=>JSON.stringify(window.__gnssLab!.project.scene))
  const bounds=(await page.locator('[data-testid=skyplot] [data-satellite-id=S01]').boundingBox())!
  await page.mouse.move(bounds.x+bounds.width/2,bounds.y+bounds.height/2);await page.mouse.down();await page.mouse.move(bounds.x+60,bounds.y+45,{steps:25});await page.mouse.up()
  const changed=await page.evaluate(()=>JSON.stringify(window.__gnssLab!.project.scene));expect(changed).not.toBe(original)
  await page.getByRole('button',{name:'撤销',exact:true}).click()
  await expect.poll(()=>page.evaluate(()=>JSON.stringify(window.__gnssLab!.project.scene))).toBe(original)
  await page.keyboard.press('Control+Shift+Z')
  await expect.poll(()=>page.evaluate(()=>JSON.stringify(window.__gnssLab!.project.scene))).toBe(changed)
})
